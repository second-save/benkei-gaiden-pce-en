def _bmp(art: str) -> bytes:
    """Convert a 16-row x 8-col '.'/'#' ASCII bitmap into 16 row bytes."""
    rows = [ln.strip() for ln in art.strip().splitlines() if ln.strip()]
    if len(rows) != 16 or any(len(r) != 8 for r in rows):
        raise ValueError(f"Expected 16x8 bitmap, got {len(rows)} rows")
    out = bytearray(16)
    for y, row in enumerate(rows):
        b = 0
        for x, ch in enumerate(row):
            if ch != ".":
                b |= 1 << (7 - x)
        out[y] = b
    return bytes(out)


def _pad(rows_3_12: tuple[str, ...], top: int = 3) -> bytes:
    """Embed compact row strings into a 16-row x 8-col glyph starting at `top`."""
    lines = ["........"] * 16
    for i, r in enumerate(rows_3_12):
        lines[top + i] = r.ljust(8, ".")[:8]
    return _bmp("\n".join(lines))


