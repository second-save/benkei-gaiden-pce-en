def patch_bg01(orig_rom: bytes) -> tuple[bytes, int]:
    """Patch BG[01] Planes 0/1 ($00..$5F) with the 8x16 English font, preserving kana/kanji/borders >= $60."""
    m = pce_gfx.bg_meta(orig_rom, 1)
    raw_tiles, orig_len = pce_gfx.decompress_stream(orig_rom, m.offset, m.count, 32, m.x_end)
    tiles = [bytearray(t) for t in raw_tiles]

    for code, rows in GLYPHS.items():
        t_top = code & 0xEF
        t_bot = code | 0x10
        plane = (code >> 4) & 1
        for y in range(8):
            tiles[t_top][y * 2 + plane] = rows[y]
            tiles[t_bot][y * 2 + plane] = rows[8 + y]

    patched_tiles = [bytes(t) for t in tiles]
    comp = pce_gfx.compress_bg(patched_tiles, m.bpp)
    redec, _ = pce_gfx.decompress_stream(comp, 0, m.count, 32, m.x_end)
    assert redec == patched_tiles, "patched BG[01] lossless roundtrip failed"
    if len(comp) > orig_len:
        raise RuntimeError(f"patched BG[01] compressed size {len(comp)} > original {orig_len}")
    return comp, orig_len


def render_preview(out_path: Path, scale: int = 3) -> None:
    """Write a zoomed preview PNG showing all 84 English 8x16 glyphs in a 16x6 grid."""
    cols, rows = 16, 6
    gw, gh = cols * 8, rows * 16
    grid = bytearray([16] * (gw * gh * 3))
    for code, bmp in GLYPHS.items():
        cx, cy = (code % cols) * 8, (code // cols) * 16
        for y in range(16):
            val = bmp[y]
            for x in range(8):
                on = (val >> (7 - x)) & 1
                col = (248, 248, 248) if on else (20, 22, 32)
                o = ((cy + y) * gw + cx + x) * 3
                grid[o : o + 3] = bytes(col)

    w, h = gw * scale, gh * scale
    scaled = bytearray(w * h * 3)
    for y in range(h):
        sy = y // scale
        for x in range(w):
            sx = x // scale
            src = (sy * gw + sx) * 3
            dst = (y * w + x) * 3
            scaled[dst : dst + 3] = grid[src : src + 3]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    pce_gfx.write_png(out_path, w, h, bytes(scaled))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--preview", type=Path, help="Write zoomed PNG preview of all glyphs")
    args = ap.parse_args()
    if args.preview:
        render_preview(args.preview)
        print(f"wrote {args.preview} ({len(GLYPHS)} glyphs)")
    return 0


